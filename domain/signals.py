"""
Domain Contract: Candidate Signal.

Standardized data structure for trading signals generated by Area B (Analysis & Strategies)
and evaluated by Area C (Simulation & Validation).
Strictly zero-lookahead: emitted on bar i close for execution at bar i+1 open.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, Optional


@dataclass
class CandidateSignal:
    """Incoming trade signal candidate with strictly zero-lookahead semantics."""

    symbol: str
    side: str  # 'LONG' or 'SHORT'
    entry_price: float
    stop_loss: float
    timestamp_ms: int
    score: float = 100.0
    metadata: Dict[str, Any] = field(default_factory=dict)
    volume: Optional[float] = None
